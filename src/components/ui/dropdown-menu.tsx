const DropdownMenuItem = React.forwardRef<
  React.ElementRef<typeof DropdownMenuPrimitive.Item>,
  React.ComponentPropsWithoutRef<typeof DropdownMenuPrimitive.Item> & {
    inset?: boolean
    /**
     * Left icon to display before the content
     */
    leftIcon?: React.ReactNode
    /**
     * Right icon to display after the content
     */
    rightIcon?: React.ReactNode
    /**
     * Whether the item is selected
     */
    selected?: boolean
    /**
     * Whether the item is destructive (red text)
     */
    destructive?: boolean
  }
>(({ 
  className, 
  inset, 
  leftIcon, 
  rightIcon, 
  selected, 
  destructive = false, 
  children, 
  ...props 
}, ref) => (
  <DropdownMenuPrimitive.Item
    ref={ref}
    className={cn(
      "relative flex cursor-default select-none items-center rounded-sm px-2 py-1.5 text-sm outline-none transition-colors focus:bg-accent focus:text-accent-foreground data-[disabled]:pointer-events-none data-[disabled]:opacity-50",
      inset && "pl-8",
      destructive && "text-destructive focus:text-destructive",
      className
    )}
    {...props}
  >
    {selected && <Check className="mr-2 h-4 w-4" />}
    {leftIcon && !selected && <span className="mr-2 h-4 w-4">{leftIcon}</span>}
    <span className="flex-1">{children}</span>
    {rightIcon && <span className="ml-2 h-4 w-4">{rightIcon}</span>}
  </DropdownMenuPrimitive.Item>
))
DropdownMenuItem.displayName = DropdownMenuPrimitive.Item.displayName

